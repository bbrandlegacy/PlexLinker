type ScriptExecution struct {
	ScriptPath      string `json:"script_path"`
	PID             int    `json:"pid"`
	ExecutionMethod string `json:"execution_method"` // "task_scheduler" or "direct"
	TaskName        string `json:"task_name"`        // For task scheduler method
	Warning         bool   `json:"warning"`          // True if fallback was used
}

type ScriptGenerator struct {
	config    *config.Config
	mediaType string // "movies" or "shows"
	showName  string // For TV shows, the existing folder name in W:\shows
}

func NewScriptGenerator(cfg *config.Config) *ScriptGenerator {
	return &ScriptGenerator{
		config:    cfg,
		mediaType: "",
		showName:  "",
	}
}

// SetMediaType sets the media type (movies/shows) and optional show name for TV shows
func (sg *ScriptGenerator) SetMediaType(mediaType, showName string) {
	sg.mediaType = mediaType
	sg.showName = showName
}

func (sg *ScriptGenerator) GenerateSimpleScript(selectedFiles map[string]*browser.DirectoryItem) (string, string, error) {
	if len(selectedFiles) == 0 {
		return "", "", fmt.Errorf("no files selected")
	}

	// Build the single-line command string (for clipboard)
	clipboardContent := sg.buildSingleLineCommand(selectedFiles)

	// Get temp directory for script
	tempDir := os.TempDir()

	// Determine file extension based on script format
	var scriptName string
	switch sg.config.ScriptFormat {
	case config.ScriptFormatBAT:
		scriptName = "plexhelper.bat"
	case config.ScriptFormatSH:
		scriptName = "plexhelper.sh"
	default:
		scriptName = "plexhelper.txt"
	}

	scriptPath := filepath.Join(tempDir, scriptName)

	// Generate script content based on format
	scriptContent := sg.buildScriptByFormat(selectedFiles)

	if err := os.WriteFile(scriptPath, []byte(scriptContent), 0755); err != nil {
		return "", "", fmt.Errorf("failed to write script file: %v", err)
	}

	return scriptPath, clipboardContent, nil
}

func (sg *ScriptGenerator) buildSingleLineCommand(selectedFiles map[string]*browser.DirectoryItem) string {
	commands := ""
	for url := range selectedFiles {
		commands += fmt.Sprintf("aria2c -x4 --http-user \"%s\" --http-passwd \"%s\" \"%s\"\n",
			sg.config.Username, sg.config.Password, url)
	}
	// Remove trailing newline for clipboard
	return strings.TrimSuffix(commands, "\n")
}

func (sg *ScriptGenerator) buildScriptByFormat(selectedFiles map[string]*browser.DirectoryItem) string {
	singleLine := sg.buildSingleLineCommand(selectedFiles)

	switch sg.config.ScriptFormat {
	case config.ScriptFormatBAT:
		return sg.buildBatchScript(singleLine)
	case config.ScriptFormatSH:
		return sg.buildShellScript(singleLine)
	default:
		return singleLine
	}
}

func (sg *ScriptGenerator) buildBatchScript(command string) string {
	script := "# aria2c download script generated by PlexLinker\n"
	script += fmt.Sprintf("# Generated on: %s\n\n", time.Now().Format("2006-01-02 15:04:05"))

	script += "$ErrorActionPreference = 'Continue'\n\n"

	// Add cd command based on media type
	if sg.mediaType == "movies" {
		script += fmt.Sprintf("Set-Location -Path '%s'\n", paths.WindowsMoviesPath)
	} else if sg.mediaType == "shows" {
		if sg.showName != "" {
			// Escape single quotes for PowerShell
			escapedName := strings.ReplaceAll(sg.showName, "'", "''")
			script += fmt.Sprintf("Set-Location -Path '%s\\%s'\n", paths.WindowsTVShowsPath, escapedName)
		} else {
			script += fmt.Sprintf("Set-Location -Path '%s'\n", paths.WindowsTVShowsPath)
		}
	}

	script += "Write-Host \"Working directory: $(Get-Location)\"\n\n"
	script += command + "\n"
	script += "\nWrite-Host \"`nAll downloads completed!\" -ForegroundColor Green\n"
	script += "Write-Host \"Press any key to close this window...\"\n"
	script += "$null = $Host.UI.RawUI.ReadKey('NoEcho,IncludeKeyDown')\n"
	return script
}

func (sg *ScriptGenerator) buildShellScript(command string) string {
	script := "#!/bin/bash\n"
	script += "# aria2c download script generated by PlexLinker\n"
	script += fmt.Sprintf("# Generated on: %s\n\n", time.Now().Format("2006-01-02 15:04:05"))

	// Add cd command based on media type (for Windows paths in Git Bash/WSL)
	if sg.mediaType == "movies" {
		script += fmt.Sprintf("cd %s\n", paths.UnixMoviesPath)
	} else if sg.mediaType == "shows" {
		if sg.showName != "" {
			// Escape single quotes and backslashes for bash
			escapedName := strings.ReplaceAll(sg.showName, "'", "'\\''")
			script += fmt.Sprintf("cd '%s/%s'\n", paths.UnixTVShowsPath, escapedName)
		} else {
			script += fmt.Sprintf("cd %s\n", paths.UnixTVShowsPath)
		}
	}

	script += "\n"
	script += command + "\n"
	script += "\necho 'All downloads completed!'\n"
	script += "read -p 'Press Enter to close...'\n"
	return script
}

// GenerateCategorizedScripts generates separate scripts for each media category
func (sg *ScriptGenerator) GenerateCategorizedScripts(
	categorized *CategorizedFiles,
	urlMapping map[string]string, // filename -> full URL
	moviesPath, tvShowsPath, otherPath string,
) ([]string, error) {
	// Resolve "auto" paths to actual platform defaults
	moviesPath = paths.ResolveAutoPath(moviesPath, "movies")
	tvShowsPath = paths.ResolveAutoPath(tvShowsPath, "tvshows")
	otherPath = paths.ResolveAutoPath(otherPath, "other")

	// Create scripts subdirectory in executable directory
	execPath, err := os.Executable()
	if err != nil {
		return nil, fmt.Errorf("failed to get executable path: %v", err)
	}
	scriptDir := filepath.Join(filepath.Dir(execPath), "scripts")

	// Create scripts directory if it doesn't exist
	if err := os.MkdirAll(scriptDir, 0755); err != nil {
		return nil, fmt.Errorf("failed to create scripts directory: %v", err)
	}

	scriptPaths := make([]string, 0)

	// Generate movies script
	if len(categorized.Movies) > 0 {
		movieURLs := make([]string, 0)
		for _, filename := range categorized.Movies {
			if url, ok := urlMapping[filename]; ok {
				movieURLs = append(movieURLs, url)
			}
		}

		// Extract name and year from first movie file
		scriptName := sg.extractCleanName(categorized.Movies[0])
		year := sg.extractYear(categorized.Movies[0])
		if year != "" {
			scriptName = scriptName + "_" + year
		}
		// Add timestamp for uniqueness
		timestamp := time.Now().Format("20060102_150405")
		scriptName = scriptName + "_" + timestamp

		scriptPath, err := sg.generateCategoryScript(movieURLs, scriptName, moviesPath, "movies", scriptDir)
		if err != nil {
			return nil, fmt.Errorf("failed to generate movies script: %v", err)
		}
		scriptPaths = append(scriptPaths, scriptPath)
	}

	// Generate TV shows script
	if len(categorized.TVShows) > 0 {
		tvURLs := make([]string, 0)
		for _, filename := range categorized.TVShows {
			if url, ok := urlMapping[filename]; ok {
				tvURLs = append(tvURLs, url)
			}
		}

		// Extract show name and season from first TV show file
		scriptName := sg.extractCleanName(categorized.TVShows[0])
		season := sg.extractSeason(categorized.TVShows[0])
		if season != "" {
			scriptName = scriptName + "_" + season
		}
		// Add timestamp for uniqueness
		timestamp := time.Now().Format("20060102_150405")
		scriptName = scriptName + "_" + timestamp

		scriptPath, err := sg.generateCategoryScript(tvURLs, scriptName, tvShowsPath, "shows", scriptDir)
		if err != nil {
			return nil, fmt.Errorf("failed to generate TV shows script: %v", err)
		}
		scriptPaths = append(scriptPaths, scriptPath)
	}

	// Generate other script
	if len(categorized.Other) > 0 {
		otherURLs := make([]string, 0)
		for _, filename := range categorized.Other {
			if url, ok := urlMapping[filename]; ok {
				otherURLs = append(otherURLs, url)
			}
		}

		// Extract name from first other file
		scriptName := sg.extractCleanName(categorized.Other[0])
		scriptPath, err := sg.generateCategoryScript(otherURLs, scriptName, otherPath, "other", scriptDir)
		if err != nil {
			return nil, fmt.Errorf("failed to generate other script: %v", err)
		}
		scriptPaths = append(scriptPaths, scriptPath)
	}

	return scriptPaths, nil
}

// generateCategoryScript creates a script for a specific category
func (sg *ScriptGenerator) generateCategoryScript(
	urls []string,
	category string,
	destPath string,
	mediaType string,
	outputDir string,
) (string, error) {
	if len(urls) == 0 {
		return "", nil
	}

	// Build command string for PowerShell (newline-separated)
	commands := ""
	for _, url := range urls {
		commands += fmt.Sprintf("aria2c -x4 --http-user \"%s\" --http-passwd \"%s\" \"%s\"\n",
			sg.config.Username, sg.config.Password, url)
	}
	// Remove trailing newline
	commands = strings.TrimSuffix(commands, "\n")

	// Determine script name and extension (always use .ps1 on Windows)
	var scriptName string
	switch sg.config.ScriptFormat {
	case config.ScriptFormatBAT:
		scriptName = fmt.Sprintf("plexhelper_%s.ps1", category)
	case config.ScriptFormatSH:
		scriptName = fmt.Sprintf("plexhelper_%s.sh", category)
	default:
		scriptName = fmt.Sprintf("plexhelper_%s.txt", category)
	}

	// Create output directory if it doesn't exist
	if err := os.MkdirAll(outputDir, 0755); err != nil {
		return "", fmt.Errorf("failed to create output directory: %v", err)
	}

	scriptPath := filepath.Join(outputDir, scriptName)

	// Build script content
	var scriptContent string
	switch sg.config.ScriptFormat {
	case config.ScriptFormatBAT:
		scriptContent = sg.buildCategoryPowerShellScript(commands, destPath, category)
	case config.ScriptFormatSH:
		scriptContent = sg.buildCategoryShellScript(commands, destPath, category)
	default:
		scriptContent = commands
	}

	// Write script with appropriate permissions
	if err := os.WriteFile(scriptPath, []byte(scriptContent), 0755); err != nil {
		return "", fmt.Errorf("failed to write script file: %v", err)
	}

	return scriptPath, nil
}

// buildCategoryPowerShellScript creates a PowerShell script for a category
func (sg *ScriptGenerator) buildCategoryPowerShellScript(command, destPath, category string) string {
	script := "# aria2c download script for " + category + " - generated by PlexLinker\n"
	script += fmt.Sprintf("# Generated on: %s\n\n", time.Now().Format("2006-01-02 15:04:05"))

	// Set error handling
	script += "$ErrorActionPreference = 'Continue'\n\n"

	// Add cd command to destination path
	if destPath != "" && destPath != "auto" {
		// Escape single quotes for PowerShell
		escapedPath := strings.ReplaceAll(destPath, "'", "''")
		script += fmt.Sprintf("Set-Location -Path '%s'\n", escapedPath)
		script += "Write-Host \"Working directory: $(Get-Location)\"\n\n"
	}

	// Add the download commands
	script += command + "\n"

	// Completion message
	script += "\nWrite-Host \"`nAll downloads completed!\" -ForegroundColor Green\n"

	// Self-delete the scheduled task if it exists
	script += "\n# Self-delete the scheduled task\n"
	script += "if ($env:PLEXLINKER_TASK_NAME) {\n"
	script += "    Start-Sleep -Seconds 2\n"
	script += "    schtasks /delete /tn $env:PLEXLINKER_TASK_NAME /f 2>$null\n"
	script += "    Write-Host \"Cleaned up task: $env:PLEXLINKER_TASK_NAME\" -ForegroundColor Gray\n"
	script += "}\n\n"

	script += "Write-Host \"Press any key to close this window...\"\n"
	script += "$null = $Host.UI.RawUI.ReadKey('NoEcho,IncludeKeyDown')\n"

	return script
}

