// extractYear extracts the year from a filename (e.g., "Movie (2024)" -> "2024")
func (sg *ScriptGenerator) extractYear(filename string) string {
	// Match 4-digit year in parentheses or brackets: (2024), [2024], or standalone 2024
	yearRegex := regexp.MustCompile(`\((\d{4})\)|\[(\d{4})\]|[\s\._](\d{4})[\s\._]`)
	matches := yearRegex.FindStringSubmatch(filename)

	for i := 1; i < len(matches); i++ {
		if matches[i] != "" {
			// Validate it's a reasonable year (1900-2099)
			year := matches[i]
			if len(year) == 4 && year[0] == '1' || year[0] == '2' {
				return year
			}
		}
	}
	return ""
}

// extractSeason extracts the season identifier from a TV show filename
func (sg *ScriptGenerator) extractSeason(filename string) string {
	lower := strings.ToLower(filename)

	// Try s01, s1 format
	seasonRegex := regexp.MustCompile(`s(\d{1,2})`)
	if matches := seasonRegex.FindStringSubmatch(lower); len(matches) > 1 {
		return "S" + fmt.Sprintf("%02s", matches[1])
	}

	// Try "season 1" format
	seasonRegex = regexp.MustCompile(`season\s*(\d{1,2})`)
	if matches := seasonRegex.FindStringSubmatch(lower); len(matches) > 1 {
		return "S" + fmt.Sprintf("%02s", matches[1])
	}

	// Try 1x01 format
	seasonRegex = regexp.MustCompile(`(\d{1,2})x\d{1,2}`)
	if matches := seasonRegex.FindStringSubmatch(lower); len(matches) > 1 {
		return "S" + fmt.Sprintf("%02s", matches[1])
	}

	return ""
}

// extractCleanName extracts a clean movie/TV show name from a filename
func (sg *ScriptGenerator) extractCleanName(filename string) string {
	// Remove file extension
	name := strings.TrimSuffix(filename, filepath.Ext(filename))

	// Common quality/release tags to remove
	qualityTags := []string{
		"1080p", "720p", "480p", "2160p", "4K", "BluRay", "BRRip", "WEB-DL", "WEBRip",
		"HDRip", "DVDRip", "x264", "x265", "h264", "h265", "HEVC", "AAC", "DD5.1",
		"DTS", "REMUX", "10bit", "8bit", "HDR", "SDR", "PROPER", "REPACK",
	}

	// Remove quality tags (case insensitive)
	lowerName := strings.ToLower(name)
	for _, tag := range qualityTags {
		lowerTag := strings.ToLower(tag)
		if idx := strings.Index(lowerName, lowerTag); idx != -1 {
			// Truncate at quality tag
			name = name[:idx]
			lowerName = lowerName[:idx]
		}
	}

	// Remove year in parentheses or brackets: (2023), [2023]
	name = strings.ReplaceAll(name, "(", " ")
	name = strings.ReplaceAll(name, ")", " ")
	name = strings.ReplaceAll(name, "[", " ")
	name = strings.ReplaceAll(name, "]", " ")

	// Remove season/episode markers for TV shows: s01, s1e1, season 1, 1x01
	seasonPatterns := []string{"s0", "s1", "s2", "s3", "s4", "s5", "s6", "s7", "s8", "s9", "season", "episode"}
	lowerName = strings.ToLower(name)
	for _, pattern := range seasonPatterns {
		if idx := strings.Index(lowerName, pattern); idx != -1 {
			name = name[:idx]
			lowerName = lowerName[:idx]
		}
	}

	// Replace dots and underscores with spaces
	name = strings.ReplaceAll(name, ".", " ")
	name = strings.ReplaceAll(name, "_", " ")
	name = strings.ReplaceAll(name, "-", " ")

	// Clean up multiple spaces
	name = strings.Join(strings.Fields(name), " ")

	// Trim whitespace
	name = strings.TrimSpace(name)

	// If name is empty or too short, use fallback
	if len(name) < 2 {
		name = "media"
	}

	// Limit length for filesystem compatibility
	if len(name) > 50 {
		name = name[:50]
	}

	// Make filesystem-safe: remove special characters
	name = strings.ReplaceAll(name, "/", "_")
	name = strings.ReplaceAll(name, "\\", "_")
	name = strings.ReplaceAll(name, ":", "_")
	name = strings.ReplaceAll(name, "*", "_")
	name = strings.ReplaceAll(name, "?", "_")
	name = strings.ReplaceAll(name, "\"", "_")
	name = strings.ReplaceAll(name, "<", "_")
	name = strings.ReplaceAll(name, ">", "_")
	name = strings.ReplaceAll(name, "|", "_")

	return name
}

// CleanupOldScripts removes scripts older than 2 days from the scripts folder
func CleanupOldScripts() error {
	// Get executable directory
	execPath, err := os.Executable()
	if err != nil {
		return fmt.Errorf("failed to get executable path: %v", err)
	}
	scriptDir := filepath.Join(filepath.Dir(execPath), "scripts")

	// Check if scripts directory exists
	if _, err := os.Stat(scriptDir); os.IsNotExist(err) {
		// Directory doesn't exist, nothing to clean
		return nil
	}

	// Read all files in scripts directory
	entries, err := os.ReadDir(scriptDir)
	if err != nil {
		return fmt.Errorf("failed to read scripts directory: %v", err)
	}

	// Get current time
	now := time.Now()
	twoDaysAgo := now.Add(-48 * time.Hour)

	// Track cleanup stats
	deletedCount := 0
	var deleteErrors []string

	// Iterate through all files
	for _, entry := range entries {
		if entry.IsDir() {
			continue // Skip subdirectories
		}

		filePath := filepath.Join(scriptDir, entry.Name())
		fileInfo, err := entry.Info()
		if err != nil {
			deleteErrors = append(deleteErrors, fmt.Sprintf("stat %s: %v", entry.Name(), err))
			continue
		}

		// Check if file is older than 2 days
		if fileInfo.ModTime().Before(twoDaysAgo) {
			if err := os.Remove(filePath); err != nil {
				deleteErrors = append(deleteErrors, fmt.Sprintf("delete %s: %v", entry.Name(), err))
			} else {
				deletedCount++
			}
		}
	}

	// If all files were deleted, remove the directory itself
	if deletedCount > 0 {
		remainingEntries, _ := os.ReadDir(scriptDir)
		if len(remainingEntries) == 0 {
			os.Remove(scriptDir)
		}
	}

	// Return any errors encountered
	if len(deleteErrors) > 0 {
		return fmt.Errorf("cleanup completed with errors: %s", strings.Join(deleteErrors, "; "))
	}

	return nil
}

// ExecuteScript launches the script in a new CMD window
func (sg *ScriptGenerator) ExecuteScript(scriptPath string, fileCount int, username string) (*ScriptExecution, error) {
	return sg.executeScriptPlatform(scriptPath, fileCount, username)
}

